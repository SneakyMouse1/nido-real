    public function run(): void
    {
        $this->command->info('🗑  Limpiando propiedades existentes...');

        // Delete in correct order to respect FKs
        DB::statement('TRUNCATE TABLE feature_property, properties RESTART IDENTITY CASCADE;');
        DB::table('media')->where('model_type', 'App\\Models\\Property')->delete();

        // ── References ──────────────────────────────────────────────────
        $agencies = Agency::whereIn('email', [
            'contact@costablanca.com',
            'info@solymar.com',
            'contact@mediterraneo.com',
        ])->get()->keyBy('email');

        $users = User::whereIn('email', [
            'manager@nidoreal.com',
            'agent@nidoreal.com',
            'agent2@nidoreal.com',
            'manager2@nidoreal.com',
            'agent3@nidoreal.com',
            'agent4@nidoreal.com',
            'manager3@nidoreal.com',
            'agent5@nidoreal.com',
        ])->get()->keyBy('email');

        $types = PropertyType::all()->keyBy('name_es');
        $features = Feature::all()->keyBy('name_es');

        if ($agencies->isEmpty() || $users->isEmpty() || $types->isEmpty()) {
            $this->command->error('Faltan datos base. Ejecuta primero los demás seeders.');

            return;
        }

        $a1 = $agencies['contact@costablanca.com'];
        $a2 = $agencies['info@solymar.com'];
        $a3 = $agencies['contact@mediterraneo.com'];

        $allProps = $this->buildProperties($a1, $a2, $a3, $users, $types);

        $done = 0;
        $total = count($allProps);

        foreach ($allProps as $entry) {
            $property = Property::create($entry['data']);

            // ── Features ──────────────────────────────────────────
            if (! empty($entry['features'])) {
                $ids = collect($entry['features'])
                    ->map(fn($name) => $features->get($name)?->id)
                    ->filter()
                    ->values()
                    ->toArray();
                $property->features()->attach($ids);
            }

            // ── Photos (Spatie Media Library) ─────────────────────────────
            if (! empty($entry['photos'])) {
                foreach ($entry['photos'] as $url) {
                    try {
                        $property->addMediaFromUrl($url)->toMediaCollection('photos');
                    } catch (\Throwable $e) {
                        $this->command->warn("  ⚠ Foto no accesible: {$url}");
                    }
                }
            }

            $done++;
            $this->command->info("  ✓ [{$done}/{$total}] {$property->title}");
        }

        // Recalculate listings_used per agency
        foreach ($agencies as $agency) {
            $agency->update(['listings_used' => $agency->properties()->count()]);
        }

        $this->command->info("✅ Seeder completado. {$done} propiedades creadas.");
    }

